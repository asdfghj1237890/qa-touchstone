function normalizeLocale(value) {
  const v = String(value || '').toLowerCase();
  if (v === 'zh-tw' || v.startsWith('zh')) return 'zh-TW';
  if (v === 'en-us' || v.startsWith('en')) return 'en-US';
  return FALLBACK_LOCALE;
}

function initialLocale() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored) return normalizeLocale(stored);
  } catch {}
  if (typeof navigator !== 'undefined') {
    return normalizeLocale(navigator.language || (navigator.languages && navigator.languages[0]));
  }
  return FALLBACK_LOCALE;
}

function formatMessage(template, vars) {
  return String(template).replace(/\{(\w+)\}/g, (m, key) => (
    vars && Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : m
  ));
}

export function I18nProvider({ children }) {
  const [locale, setLocaleState] = React.useState(initialLocale);
  const setLocale = React.useCallback((next) => {
    const normalized = normalizeLocale(next);
    setLocaleState(normalized);
    try { localStorage.setItem(STORAGE_KEY, normalized); } catch {}
  }, []);
  React.useEffect(() => {
    if (typeof document !== 'undefined') document.documentElement.lang = locale;
  }, [locale]);
  const value = React.useMemo(() => ({
    locale,
    setLocale,
    t: (key, vars) => formatMessage((dict[locale] && dict[locale][key]) || dict[FALLBACK_LOCALE][key] || key, vars),
  }), [locale, setLocale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
